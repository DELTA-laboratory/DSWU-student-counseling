/**
 * 특정 날짜("YYYY-MM-DD")가 대한민국 법정공휴일인지 판별하고 공휴일명을 반환합니다.
 */
export function getKoreanHoliday(dateStr: string): HolidayInfo {
  if (!dateStr || dateStr.length < 10) {
    return { isHoliday: false };
  }

  // 1. 사전 정의된 공휴일 목록 확인
  if (KOREAN_HOLIDAYS[dateStr]) {
    return { isHoliday: true, name: KOREAN_HOLIDAYS[dateStr] };
  }

  // 2. 사전에 등록되지 않은 연도(예: 2029년 이후)를 위한 일반 양력 공휴일 폴백
  const parts = dateStr.split('-');
  if (parts.length === 3) {
    const year = parseInt(parts[0], 10);
    const mmdd = `${parts[1]}-${parts[2]}`;

    const fixedHolidays: Record<string, string> = {
      '01-01': '신정',
      '03-01': '3·1절',
      '05-05': '어린이날',
      '06-06': '현충일',
      '07-17': '제헌절',
      '08-15': '광복절',
      '10-03': '개천절',
      '10-09': '한글날',
      '12-25': '성탄절',
    };

    if (fixedHolidays[mmdd]) {
      // 2026년 이전 제헌절 제외
      if (mmdd === '07-17' && year < 2026) {
        return { isHoliday: false };
      }
      return { isHoliday: true, name: fixedHolidays[mmdd] };
    }
  }

  return { isHoliday: false };
}

/**
 * 특정 날짜가 법정공휴일인지 여부 (boolean)
 */
export function isKoreanHoliday(dateStr: string): boolean {
  return getKoreanHoliday(dateStr).isHoliday;
}

/**
 * 특정 날짜의 법정공휴일 이름 (없을 시 null)
 */
export function getKoreanHolidayName(dateStr: string): string | null {
  const info = getKoreanHoliday(dateStr);
  return info.isHoliday ? (info.name || '법정공휴일') : null;
}
